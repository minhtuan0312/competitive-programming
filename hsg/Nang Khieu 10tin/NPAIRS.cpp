ll bin_pow(ll a, ll b, ll m) {
    ll res = 1;
    a = a % m;
    while(b) {
        if(b & 1) res = res * a % m;
        a = a * a % m;
        b >>= 1;
    }
    return res;
}

void solve() {

    ll n, m; cin >> n >> m;
    ll q = n / m;
    ll r = n % m;
    ll res = 0;
    //TH1
    res += q * (q - 1) / 2;
    //TH2
    if(!(m & 1)) {
        ll tmp = q;
        ll half = (m >> 1);
        if(half <= r) tmp++;
        res += tmp * (tmp - 1) / 2;
    }
    //TH3
    ll cnt = (m - 1) / 2;
    res += cnt * q * q;
    res += q * max(0ll, cnt - max(1ll, m - r) + 1);
    res += q * min(cnt, r);
    res += max(0ll, min(r, cnt) - max(1ll, m - r) + 1);
    cout << res << nl;

}

